def build_payload(current_version: str) -> dict[str, Any]:
    """组装给前端的载荷：整份日志 + 标出哪条是当前版本。"""
    cur = str(current_version or "").strip()
    entries: list[dict[str, Any]] = []
    for row in CHANGELOG:
        ver = str(row.get("version") or "").strip()
        items = [str(x).strip() for x in (row.get("items") or []) if str(x).strip()]
        entries.append(
            {
                "version": ver,
                "date": str(row.get("date") or "").strip(),
                "items": items,
                "current": bool(cur) and ver == cur,
            }
        )
    return {
        "ok": True,
        "current": cur,
        "has_current": any(e["current"] for e in entries),
        "entries": entries,
    }
